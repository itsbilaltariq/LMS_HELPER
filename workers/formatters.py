"""Multi-format deliverable generators for Jupyter Notebooks, Word, and Excel."""

import json
from pathlib import Path
from typing import Any

from app.logging import setup_logging

logger = setup_logging()


def build_notebook_structure(
    cells: list[dict[str, Any]],
    kernel_name: str = "python3",
    language: str = "python",
) -> dict[str, Any]:
    """
    Construct a compliant Jupyter Notebook (nbformat v4) dictionary.
    """
    formatted_cells = []
    for cell in cells:
        cell_type = cell.get("cell_type", "code")
        source = cell.get("source", "")

        # Source must be a list of lines in nbformat v4
        if isinstance(source, str):
            source_lines = [line + "\n" for line in source.splitlines()]
            if source_lines:
                source_lines[-1] = source_lines[-1].rstrip("\n")
        else:
            source_lines = list(source)

        if cell_type == "markdown":
            formatted_cells.append(
                {
                    "cell_type": "markdown",
                    "metadata": {},
                    "source": source_lines,
                }
            )
        else:
            formatted_cells.append(
                {
                    "cell_type": "code",
                    "execution_count": cell.get("execution_count", None),
                    "metadata": {},
                    "outputs": cell.get("outputs", []),
                    "source": source_lines,
                }
            )

    return {
        "cells": formatted_cells,
        "metadata": {
            "kernelspec": {
                "display_name": f"Python ({kernel_name})",
                "language": language,
                "name": kernel_name,
            },
            "language_info": {
                "name": language,
                "version": "3.12",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def create_jupyter_notebook(
    cells: list[dict[str, Any]],
    output_path: str | Path,
    kernel_name: str = "python3",
) -> Path:
    """Write cells into a validated .ipynb Jupyter notebook file."""
    nb_dict = build_notebook_structure(cells, kernel_name=kernel_name)
    target = Path(output_path).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)

    with open(target, "w", encoding="utf-8") as f:
        json.dump(nb_dict, f, indent=2)

    logger.info(f"Created Jupyter notebook deliverable: {target.name}")
    return target


def convert_solution_to_notebook(
    title: str,
    solution_code: str,
    walkthrough: str,
    output_path: str | Path,
    viva_questions: list[str] | None = None,
) -> Path:
    """Generate a submission-ready .ipynb with documentation, solution code, and viva prep."""
    cells: list[dict[str, Any]] = [
        {
            "cell_type": "markdown",
            "source": (
                f"# {title}\n*Generated by NUST LMS Lab Helper*\n\n"
                f"## 1. Overview & Walkthrough\n{walkthrough}"
            ),
        },
        {
            "cell_type": "markdown",
            "source": "## 2. Implementation Code",
        },
        {
            "cell_type": "code",
            "source": solution_code,
        },
    ]

    if viva_questions:
        viva_md = "\n".join([f"- {q}" for q in viva_questions])
        cells.append(
            {
                "cell_type": "markdown",
                "source": f"## 3. Viva / Examination Preparation\n{viva_md}",
            }
        )

    return create_jupyter_notebook(cells, output_path)
