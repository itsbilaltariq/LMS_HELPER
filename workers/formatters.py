"""Multi-format deliverable generators for Jupyter Notebooks, Word, and Excel."""

import json
from pathlib import Path
from typing import Any

from docx import Document
from openpyxl import Workbook

from app.logging import setup_logging

logger = setup_logging()


def build_notebook_structure(
    cells: list[dict[str, Any]],
    kernel_name: str = "python3",
    language: str = "python",
) -> dict[str, Any]:
    """
    Construct a compliant Jupyter Notebook (nbformat v4) dictionary.
    """
    formatted_cells = []
    for cell in cells:
        cell_type = cell.get("cell_type", "code")
        source = cell.get("source", "")

        # Source must be a list of lines in nbformat v4
        if isinstance(source, str):
            source_lines = [line + "\n" for line in source.splitlines()]
            if source_lines:
                source_lines[-1] = source_lines[-1].rstrip("\n")
        else:
            source_lines = list(source)

        if cell_type == "markdown":
            formatted_cells.append(
                {
                    "cell_type": "markdown",
                    "metadata": {},
                    "source": source_lines,
                }
            )
        else:
            formatted_cells.append(
                {
                    "cell_type": "code",
                    "execution_count": cell.get("execution_count", None),
                    "metadata": {},
                    "outputs": cell.get("outputs", []),
                    "source": source_lines,
                }
            )

    return {
        "cells": formatted_cells,
        "metadata": {
            "kernelspec": {
                "display_name": f"Python ({kernel_name})",
                "language": language,
                "name": kernel_name,
            },
            "language_info": {
                "name": language,
                "version": "3.12",
            },
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def create_jupyter_notebook(
    cells: list[dict[str, Any]],
    output_path: str | Path,
    kernel_name: str = "python3",
) -> Path:
    """Write cells into a validated .ipynb Jupyter notebook file."""
    nb_dict = build_notebook_structure(cells, kernel_name=kernel_name)
    target = Path(output_path).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)

    with open(target, "w", encoding="utf-8") as f:
        json.dump(nb_dict, f, indent=2)

    logger.info(f"Created Jupyter notebook deliverable: {target.name}")
    return target


def convert_solution_to_notebook(
    title: str,
    solution_code: str,
    walkthrough: str,
    output_path: str | Path,
    viva_questions: list[str] | None = None,
) -> Path:
    """Generate a submission-ready .ipynb with documentation, solution code, and viva prep."""
    cells: list[dict[str, Any]] = [
        {
            "cell_type": "markdown",
            "source": (
                f"# {title}\n*Generated by NUST LMS Lab Helper*\n\n"
                f"## 1. Overview & Walkthrough\n{walkthrough}"
            ),
        },
        {
            "cell_type": "markdown",
            "source": "## 2. Implementation Code",
        },
        {
            "cell_type": "code",
            "source": solution_code,
        },
    ]

    if viva_questions:
        viva_md = "\n".join([f"- {q}" for q in viva_questions])
        cells.append(
            {
                "cell_type": "markdown",
                "source": f"## 3. Viva / Examination Preparation\n{viva_md}",
            }
        )

    return create_jupyter_notebook(cells, output_path)


def create_word_document(
    title: str,
    sections: list[dict[str, Any]],
    output_path: str | Path,
) -> Path:
    """Create a structured Word document (.docx) for lab reports or deliverables."""
    doc = Document()
    doc.add_heading(title, level=0)

    for sec in sections:
        heading = sec.get("heading", "")
        content = sec.get("content", "")
        is_code = sec.get("is_code", False)

        if heading:
            doc.add_heading(heading, level=1)

        if content:
            if is_code:
                p = doc.add_paragraph()
                run = p.add_run(content)
                run.font.name = "Courier New"
            else:
                doc.add_paragraph(content)

    target = Path(output_path).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    doc.save(str(target))
    logger.info(f"Created Word document deliverable: {target.name}")
    return target


def convert_solution_to_word(
    title: str,
    solution_code: str,
    walkthrough: str,
    output_path: str | Path,
    viva_questions: list[str] | None = None,
) -> Path:
    """Convert solution code and explanations into a formatted Word lab report."""
    sections: list[dict[str, Any]] = [
        {"heading": "1. Solution Overview & Walkthrough", "content": walkthrough},
        {"heading": "2. Implementation Code", "content": solution_code, "is_code": True},
    ]

    if viva_questions:
        viva_text = "\n".join([f"{idx + 1}. {q}" for idx, q in enumerate(viva_questions)])
        sections.append({"heading": "3. Viva Examination Preparation", "content": viva_text})

    return create_word_document(title, sections, output_path)


def create_excel_spreadsheet(
    sheets_data: dict[str, list[list[Any]]],
    output_path: str | Path,
) -> Path:
    """Create an Excel spreadsheet (.xlsx) with named sheets and table rows."""
    wb = Workbook()
    first_sheet = True

    for sheet_name, rows in sheets_data.items():
        if first_sheet:
            ws = wb.active
            if ws is not None:
                ws.title = sheet_name
            else:
                ws = wb.create_sheet(title=sheet_name)
            first_sheet = False
        else:
            ws = wb.create_sheet(title=sheet_name)

        for row in rows:
            ws.append(row)

    target = Path(output_path).resolve()
    target.parent.mkdir(parents=True, exist_ok=True)
    wb.save(str(target))
    logger.info(f"Created Excel deliverable: {target.name}")
    return target
